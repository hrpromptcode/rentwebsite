import "../../../load-env";
import { chromium } from "@playwright/test";
import { isolateHmr } from "./_dev-stable";
/** reverify-storefront: replay restaurant-journey 3.1/3.2 (pickup PromptPay order + slip) and print React key warnings in full. */
const PNG = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==", "base64");
async function main() {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, reducedMotion: "reduce", hasTouch: true, isMobile: true, locale: "th-TH" });
  await isolateHmr(ctx);
  const page = await ctx.newPage();
  let stage = "order";
  page.on("console", async (m) => {
    if (m.type() !== "error" && m.type() !== "warning") return;
    const args = await Promise.all(m.args().map((a) => a.jsonValue().catch(() => "?")));
    console.log(`[${stage}] [${m.type()}] ${args.map((a) => String(a)).join(" ").slice(0, 2500)}\n-----`);
  });
  page.on("pageerror", (e) => console.log(`[${stage}] [pageerror] ${e.message.slice(0, 1500)}`));
  const BASE = "http://demo-restaurant.localhost:3000";
  await page.goto(`${BASE}/order`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: /หมูสะเต๊ะสูตรคุณยาย/ }).click();
  await page.getByRole("dialog").getByRole("button", { name: /เพิ่มในออเดอร์/ }).click();
  await page.locator("[data-rw-cartbar] button").click();
  const dlg = page.getByRole("dialog");
  await dlg.getByRole("button", { name: /ดำเนินการต่อ/ }).click();
  await dlg.getByRole("radiogroup", { name: "เวลารับอาหาร" }).getByRole("radio").nth(1).click();
  await dlg.locator("#pickup-name").fill("คุณโพรบ คีย์");
  await dlg.locator("#pickup-phone").fill("0812345678");
  await dlg.getByRole("button", { name: /ยืนยันสั่งอาหาร/ }).click();
  await page.waitForURL(/\/orders\/r\/R-\d+\?p=/, { timeout: 30000 });
  stage = "tracker";
  await page.waitForLoadState("networkidle");
  await page.waitForTimeout(1500);
  stage = "slip";
  await page.locator('input[type="file"]').setInputFiles({ name: "slip.png", mimeType: "image/png", buffer: PNG });
  await page.getByText("ได้รับสลิปแล้ว รอตรวจสอบ").waitFor({ timeout: 20000 });
  await page.waitForTimeout(4000);
  stage = "reload";
  await page.reload({ waitUntil: "networkidle" });
  await page.waitForTimeout(1500);
  const pickupNumber = page.url().match(/R-\d+/)![0];
  stage = "cash";
  await page.goto(`${BASE}/order`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: /ปอเปี๊ยะทอดผัก/ }).click();
  await page.getByRole("dialog").getByRole("button", { name: /เพิ่มในออเดอร์/ }).click();
  await page.locator("[data-rw-cartbar] button").click();
  const d2 = page.getByRole("dialog");
  await d2.getByRole("button", { name: /ดำเนินการต่อ/ }).click();
  await d2.getByRole("radiogroup", { name: "เวลารับอาหาร" }).getByRole("radio").first().click();
  await d2.locator("#pickup-name").fill("คุณเงินสด");
  await d2.locator("#pickup-phone").fill("0812345678");
  await d2.locator("label", { hasText: "เงินสดเมื่อมารับ" }).click();
  await d2.getByRole("button", { name: /ยืนยันสั่งอาหาร/ }).click();
  await page.waitForURL(/\/orders\/r\/R-\d+\?p=/, { timeout: 30000 });
  await page.waitForTimeout(2000);
  stage = "wrongphone";
  await page.goto(`${BASE}/orders/r/${pickupNumber}?p=0800000000`, { waitUntil: "networkidle" });
  stage = "lookup";
  await page.goto(`${BASE}/orders/r/lookup`, { waitUntil: "networkidle" });
  await page.locator("#lookup-n").fill(pickupNumber.toLowerCase());
  await page.locator("#lookup-p").fill("0812345678");
  await page.getByRole("button", { name: /ติดตามออเดอร์/ }).click();
  await page.waitForURL(new RegExp(`/orders/r/${pickupNumber}\?p=`), { timeout: 15000 });
  await page.waitForTimeout(2000);
  console.log("done", page.url());
  await b.close();
}
main();
