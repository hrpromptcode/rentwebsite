/** sections agent: admin page-builder + design editor screenshots (add dialog thumbnails, Thai option labels, effects tab). */
import { chromium } from "@playwright/test";
const A = "http://localhost:3001";
const SLUG = process.argv[2] ?? "demo-corporate";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
const p = await ctx.newPage();
const errs: string[] = [];
p.on("console", (m) => (m.type() === "error" || /hydrat/i.test(m.text())) && errs.push(m.text().slice(0, 200)));
p.on("pageerror", (e) => errs.push("pageerror " + e.message.slice(0, 200)));
await p.goto(`${A}/login`, { waitUntil: "load", timeout: 120_000 });
await p.fill("#email", "admin@rentweb.local");
await p.fill("#password", "Admin1234!");
await Promise.all([p.waitForURL((u) => !u.pathname.startsWith("/login"), { timeout: 90_000 }), p.getByRole("button", { name: "เข้าสู่ระบบ" }).click()]);
await p.goto(`${A}/t/${SLUG}/pages`, { waitUntil: "load", timeout: 120_000 });
const href = await p.locator(`a[href^='/t/${SLUG}/pages/']`).first().getAttribute("href");
await p.goto(`${A}${href}`, { waitUntil: "load", timeout: 120_000 });
await p.getByText("เซ็กชัน", { exact: false }).first().waitFor({ timeout: 60_000 });
await p.locator("ol.divide-y > li button.flex-1").first().click();
await p.waitForTimeout(800);
await p.screenshot({ path: "screenshots/redesign-sections-admin-hero-form.png", fullPage: true });
await p.getByRole("button", { name: "เพิ่มเซ็กชัน" }).first().click();
const dialog = p.getByRole("dialog").filter({ hasText: "เพิ่มเซ็กชัน" });
await dialog.waitFor({ state: "visible" });
await p.waitForTimeout(500);
await p.screenshot({ path: "screenshots/redesign-sections-admin-add-dialog.png" });
// add a sticky story to see its auto-form (nested chips array)
await dialog.getByLabel("ค้นหาเซ็กชัน").fill("Sticky");
await dialog.locator("button").filter({ hasText: "เรื่องเล่าแบบเลื่อนติด" }).first().click();
await dialog.waitFor({ state: "hidden" });
await p.getByRole("button", { name: "เพิ่มรายการ" }).first().click();
await p.waitForTimeout(600);
await p.screenshot({ path: "screenshots/redesign-sections-admin-sticky-form.png", fullPage: true });
await p.goto(`${A}/t/${SLUG}/design`, { waitUntil: "load", timeout: 120_000 });
await p.getByRole("tab", { name: "เอฟเฟกต์" }).click();
await p.waitForTimeout(600);
await p.screenshot({ path: "screenshots/redesign-sections-admin-effects.png" });
await p.getByRole("tab", { name: "ฟอนต์" }).click();
await p.waitForTimeout(400);
await p.screenshot({ path: "screenshots/redesign-sections-admin-fonts.png" });
console.log("errors", errs.length, [...new Set(errs)].slice(0, 5).join(" | "));
await b.close();
