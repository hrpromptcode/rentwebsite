export type LabelKey = keyof typeof L;

export function label(key: LabelKey, vars?: Record<string, string | number>): string {
  let s: string = L[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

